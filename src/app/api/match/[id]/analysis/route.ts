/**
 * AI Match Analysis endpoints for one event.
 *
 * Prediction (pre-match) document — the default kind:
 *   GET  /api/match/[id]/analysis                     -> retrieve the stored analysis
 *   POST /api/match/[id]/analysis                     -> analyse (returns the stored
 *                                                        analysis while it is fresh)
 *   POST /api/match/[id]/analysis?refresh=1           -> force regeneration
 *   POST /api/match/[id]/analysis?lang=ar             -> also mirror the report text
 *                                                        into Arabic (translated once,
 *                                                        then stored)
 *
 * Historical (retrospective) document — `kind=past`, finished matches only:
 *   GET  /api/match/[id]/analysis?kind=past           -> retrieve the stored retrospective
 *   POST /api/match/[id]/analysis?kind=past           -> analyse the finished match
 *   POST /api/match/[id]/analysis?kind=past&refresh=1 -> force regeneration
 *   POST /api/match/[id]/analysis?kind=past&lang=ar   -> Arabic mirror (stored in place)
 *
 * Football statistics come from ESPN's public APIs (the football data
 * provider); reasoning and prediction generation happen exclusively in
 * Touchline AI, behind the backend. The AI credentials never leave this
 * process and never appear in responses or logs.
 */
import { NextResponse, connection } from "next/server";
import {
  analysisFailure,
  ensureAnalysisLanguage,
  getStoredAnalysis,
  isStoredFresh,
  type AnalysisLanguage,
  type StoredAnalysis,
} from "@/lib/analysis/analyze";
import { clientIdentity, rateLimitReject } from "@/lib/analysis/rate-limit";
import {
  ensureHistoricalLanguage,
  getStoredHistorical,
  isHistoricalFresh,
  type StoredHistorical,
} from "@/lib/analysis/retrospective";
import { apiBadRequest, apiError, apiNotFound, apiOk } from "@/lib/api-response";
import { isTeamId } from "@/lib/validation";
import type { ApiMeta } from "@/lib/types";

/**
 * Long enough for a full dataset build plus a (retried) LLM completion, or a
 * generation followed by the on-demand Arabic translation pass.
 */
export const maxDuration = 120;

const ANALYSIS_ATTRIBUTION =
  "Prediction generated by Touchline AI from statistics provided by ESPN's public APIs. Touchline AI analyses provider data; it is not affiliated with ESPN.";

const HISTORICAL_ATTRIBUTION =
  "Retrospective generated by Touchline AI from facts extracted in code from ESPN's published match data. Touchline AI analyses provider data; it is not affiliated with ESPN.";

/** `kind` is absent (prediction) or `past` (historical); anything else is a 400. */
function kindOf(searchParams: URLSearchParams): "prediction" | "past" | null {
  const kind = searchParams.get("kind");
  if (kind === null) return "prediction";
  if (kind === "past") return "past";
  return null;
}

function metaFor(
  cacheSeconds: number,
  fetchedAt?: string,
  attribution: string = ANALYSIS_ATTRIBUTION,
): ApiMeta {
  return {
    source: "Touchline AI",
    attribution,
    fetchedAt: fetchedAt ?? new Date().toISOString(),
    cacheSeconds,
  };
}

