/**
 * AI Match Analysis endpoints for one event.
 *
 *   GET  /api/match/[id]/analysis            -> retrieve the stored analysis
 *   POST /api/match/[id]/analysis            -> analyse (returns the stored
 *                                               analysis while it is fresh)
 *   POST /api/match/[id]/analysis?refresh=1  -> force regeneration
 *   POST /api/match/[id]/analysis?lang=ar    -> also mirror the report text
 *                                               into Arabic (translated once,
 *                                               then stored)
 *
 * Football statistics come from ESPN's public APIs (the football data
 * provider); reasoning and prediction generation happen exclusively in
 * FFC-Vision, behind the backend. The gateway API key never leaves this
 * process and never appears in responses or logs.
 */
import { NextResponse, connection } from "next/server";
import { getAiConfig } from "@/lib/ai/config";
import {
  analysisFailure,
  ensureAnalysisLanguage,
  getStoredAnalysis,
  isStoredFresh,
  type AnalysisLanguage,
  type StoredAnalysis,
} from "@/lib/analysis/analyze";
import { apiBadRequest, apiError, apiNotFound, apiOk } from "@/lib/api-response";
import { isTeamId } from "@/lib/validation";
import type { ApiMeta } from "@/lib/types";

/**
 * Long enough for a full dataset build plus a (retried) LLM completion, or a
 * generation followed by the on-demand Arabic translation pass.
 */
export const maxDuration = 120;

const ANALYSIS_ATTRIBUTION =
  "Prediction generated by FFC-Vision from statistics provided by ESPN's public APIs. FFC-Vision analyses provider data; it is not affiliated with ESPN.";

function metaFor(cacheSeconds: number, fetchedAt?: string): ApiMeta {
  return {
    source: "FFC AI Gateway (FFC-Vision)",
    attribution: ANALYSIS_ATTRIBUTION,
    fetchedAt: fetchedAt ?? new Date().toISOString(),
    cacheSeconds,
  };
}

/* ----------------------------------------------------------------------- */
/* Per-client rate limit for generation (the gateway call is the cost).     */
/* ------------------------------------------------------------------------ */

const generationHits = new Map<string, number[]>();

function clientIdentity(request: Request): string {
  const forwarded = request.headers.get("x-forwarded-for");
  return forwarded?.split(",")[0]?.trim() || "local";
}

function rateLimitReject(identity: string): boolean {
  const config = getAiConfig();
  const now = Date.now();
  const windowStart = now - 60 * 60 * 1000;
  const hits = (generationHits.get(identity) ?? []).filter(
    (hit) => hit > windowStart,
  );
  if (hits.length >= config.rateLimitPerHour) {
    generationHits.set(identity, hits);
    return true;
  }
  hits.push(now);
  generationHits.set(identity, hits);
  return false;
}

/* ----------------------------------------------------------------------- */
/* Handlers                                                                 */
/* ------------------------------------------------------------------------ */

/** GET /api/match/[id]/analysis — the stored analysis, if one exists. */
export async function GET(
  _request: Request,
  context: { params: Promise<{ id: string }> },
) {
  const { id } = await context.params;
  if (!isTeamId(id)) {
    return apiNotFound("Match ids are numeric ESPN event ids.");
  }

  // Always read request-time: a newly generated analysis must be visible on
  // the very next GET instead of a prerendered static snapshot.
  await connection();

  try {
    const analysis = await getStoredAnalysis(id);
    if (!analysis) {
      return apiNotFound(
        "No analysis has been generated for that match yet.",
      );
    }
    return toResponse(analysis);
  } catch (error) {
    return apiError(error, "The stored analysis could not be read.");
  }
}

/** POST /api/match/[id]/analysis — analyse the fixture with FFC-Vision. */
export async function POST(
  request: Request,
  context: { params: Promise<{ id: string }> },
) {
  const { id } = await context.params;
  if (!isTeamId(id)) {
    return apiNotFound("Match ids are numeric ESPN event ids.");
  }

  const params = new URL(request.url).searchParams;
  const refresh = params.get("refresh");
  if (refresh !== null && refresh !== "1") {
    return apiBadRequest("The refresh parameter accepts the value 1 only.");
  }
  const lang = params.get("lang");
  if (lang !== null && lang !== "ar") {
    return apiBadRequest("The lang parameter accepts the value ar only.");
  }
  const language: AnalysisLanguage = lang === "ar" ? "ar" : "en";

  // The POST body is optional; only `{ "refresh": true }` is meaningful.
  let bodyRefresh = false;
  try {
    const body: unknown = await request.json();
    if (Array.isArray(body) || body === null) bodyRefresh = false;
    else if (typeof body === "object" && (body as { refresh?: unknown }).refresh === true) {
      bodyRefresh = true;
    }
  } catch {
    // Empty or malformed body: treat as a plain generate request.
  }

  try {
    const refreshRequested = refresh === "1" || bodyRefresh;

    // The limiter budgets gateway calls, not file reads: a fresh stored
    // analysis is served without consuming a per-client generation slot.
    // An Arabic request still reaches the gateway while the stored analysis
    // has no Arabic mirror yet — producing one is gateway work.
    if (!refreshRequested) {
      const stored = await getStoredAnalysis(id);
      if (
        stored &&
        isStoredFresh(stored) &&
        (language === "en" || stored.translation)
      ) {
        return toResponse(stored);
      }
    }

    if (rateLimitReject(clientIdentity(request))) {
      return NextResponse.json(
        {
          error: {
            message:
              "Analysis regeneration limit reached for this client. Stored analyses remain available.",
            status: 429,
            code: "rate_limited",
          },
        },
        { status: 429, headers: { "Cache-Control": "no-store" } },
      );
    }

    const analysis = await ensureAnalysisLanguage(id, {
      refresh: refreshRequested,
      language,
    });
    return toResponse(analysis);
  } catch (error) {
    const failure = analysisFailure(error);
    return NextResponse.json(
      { error: { message: failure.message, status: failure.status, code: failure.code } },
      { status: failure.status, headers: { "Cache-Control": "no-store" } },
    );
  }
}

function toResponse(analysis: StoredAnalysis) {
  return apiOk(analysis, metaFor(0, analysis.generatedAt), 0);
}
