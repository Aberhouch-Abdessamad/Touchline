/**
 * AI Live Match Analyst endpoints for one in-play match.
 *
 *   GET  /api/match/[id]/live                 -> the stored live document
 *                                                (404 until the first capture;
 *                                                after the final whistle the
 *                                                first GET also computes and
 *                                                stores the final report)
 *   POST /api/match/[id]/live                 -> capture the current in-play
 *                                                state when a trigger
 *                                                justifies it
 *   POST /api/match/[id]/live?refresh=1       -> force a capture ("manual")
 *   POST /api/match/[id]/live?lang=ar         -> also mirror the latest
 *                                                snapshot into Arabic
 *   POST /api/match/[id]/live  {"refresh":true} -> same as ?refresh=1
 *
 * The capture endpoints are rate-limited per client and only consume a
 * rate-limit slot when a real AI capture will actually run — reads and
 * no-op ("skipped"/"unchanged") responses stay free. Requests for matches
 * that are not in play are refused with 409 `match_not_live`.
 *
 * Credentials live only in the server environment and never appear in
 * responses, logs or this file.
 */
import { NextResponse, connection } from "next/server";
import {
  captureLive,
  ensureLiveLanguage,
  finalizeLiveReport,
  getStoredLive,
  liveFailure,
} from "@/lib/analysis/live";
import {
  RateLimitExceededError,
  clientIdentity,
  rateLimitReject,
} from "@/lib/analysis/rate-limit";
import { apiBadRequest, apiNotFound, apiOk } from "@/lib/api-response";
import { isTeamId } from "@/lib/validation";
import type { LiveFacts } from "@/lib/analysis/live-dataset";
import type { ApiMeta } from "@/lib/types";

/**
 * Long enough for a lived dataset build plus a (retried) LLM completion, or
 * a capture followed by the on-demand Arabic translation pass.
 */
export const maxDuration = 120;

const LIVE_ATTRIBUTION =
  "Live analysis generated by Touchline AI from facts extracted in code from ESPN's published match data. Touchline AI analyses provider data; it is not affiliated with ESPN.";

const LIVE_LIMIT_MESSAGE =
  "Live analysis capture limit reached for this client. The last stored analysis remains available.";

/** Seconds the client should wait before its next capture poll. */
const LIVE_POLL_AFTER_SECONDS = 30;

function metaFor(fetchedAt?: string): ApiMeta {
  return {
    source: "Touchline AI",
    attribution: LIVE_ATTRIBUTION,
    fetchedAt: fetchedAt ?? new Date().toISOString(),
    cacheSeconds: 0,
    pollAfterSeconds: LIVE_POLL_AFTER_SECONDS,
  };
}

/** The match header the dashboard's live page needs (logos, colours, score). */
function liveMatchHeader(facts: LiveFacts) {
  const { match } = facts;
  return {
    id: match.id,
    name: match.name,
    kickoff: match.kickoff,
    state: match.state,
    statusLabel: match.statusLabel,
    competition: match.competition,
    minuteLabel: facts.minuteLabel,
    score: facts.score,
    home: match.home,
    away: match.away,
  };
}

function failureResponse(error: unknown) {
  const failure = liveFailure(error);
  return NextResponse.json(
    {
      error: { message: failure.message, status: failure.status, code: failure.code },
    },
    { status: failure.status, headers: { "Cache-Control": "no-store" } },
  );
}

/** GET /api/match/[id]/live — the stored live document, if one exists. */
export async function GET(
  request: Request,
  context: { params: Promise<{ id: string }> },
) {
  const { id } = await context.params;
  if (!isTeamId(id)) {
    return apiNotFound("Match ids are numeric ESPN event ids.");
  }

  const lang = new URL(request.url).searchParams.get("lang");
  if (lang !== null && lang !== "ar") {
    return apiBadRequest("The lang parameter accepts the value ar only.");
  }

  await connection();

  try {
    let doc = await getStoredLive(id);
    if (!doc) {
      return apiNotFound(
        "No live analysis has been captured for that match yet.",
      );
    }
    // First GET that observes the final whistle stores the final report.
    doc = (await finalizeLiveReport(id)) ?? doc;
    if (lang === "ar") doc = (await ensureLiveLanguage(id, "ar")) ?? doc;
    return apiOk({ live: doc }, metaFor(doc.updatedAt), 0);
  } catch (error) {
    return failureResponse(error);
  }
}

/** POST /api/match/[id]/live — capture the current in-play state. */
export async function POST(
  request: Request,
  context: { params: Promise<{ id: string }> },
) {
  const { id } = await context.params;
  if (!isTeamId(id)) {
    return apiNotFound("Match ids are numeric ESPN event ids.");
  }

  const params = new URL(request.url).searchParams;
  const refresh = params.get("refresh");
  if (refresh !== null && refresh !== "1") {
    return apiBadRequest("The refresh parameter accepts the value 1 only.");
  }
  const lang = params.get("lang");
  if (lang !== null && lang !== "ar") {
    return apiBadRequest("The lang parameter accepts the value ar only.");
  }

  // The POST body is optional; only `{ "refresh": true }` is meaningful.
  let bodyRefresh = false;
  try {
    const body: unknown = await request.json();
    if (!Array.isArray(body) && body !== null) {
      const refreshBody = (body as { refresh?: unknown }).refresh;
      if (refreshBody !== undefined && typeof refreshBody !== "boolean") {
        return apiBadRequest("The refresh body field accepts booleans only.");
      }
      bodyRefresh = refreshBody === true;
    }
  } catch {
    // Empty or malformed body: treat as a plain capture request.
  }

  await connection();

  try {
    const capture = await captureLive(id, {
      refresh: refresh === "1" || bodyRefresh,
      language: lang === "ar" ? "ar" : "en",
      gate: () => {
        // Only reached when a real gateway capture is about to run.
        if (rateLimitReject(clientIdentity(request))) {
          throw new RateLimitExceededError(LIVE_LIMIT_MESSAGE);
        }
      },
    });
    return apiOk(
      {
        status: capture.status,
        ...(capture.trigger ? { trigger: capture.trigger } : {}),
        ...(capture.reason ? { reason: capture.reason } : {}),
        match: liveMatchHeader(capture.facts),
        live: capture.doc,
      },
      metaFor(capture.doc?.updatedAt),
      0,
    );
  } catch (error) {
    return failureResponse(error);
  }
}